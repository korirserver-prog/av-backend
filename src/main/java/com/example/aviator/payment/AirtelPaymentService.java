package com.example.aviator.payment;

import com.example.aviator.payment.dto.AirtelPaymentRequest;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.http.*;
import org.springframework.stereotype.Service;
import org.springframework.web.client.RestTemplate;

import java.util.HashMap;
import java.util.Map;
import java.util.UUID;

@Service
public class AirtelPaymentService {

    @Value("${airtel.base-url}")
    private String baseUrl;

    @Value("${airtel.country}")
    private String country;

    @Value("${airtel.currency}")
    private String currency;

    private final AirtelAuthService airtelAuthService;
    private final RestTemplate restTemplate;

    public AirtelPaymentService(
            AirtelAuthService airtelAuthService
    ) {
        this.airtelAuthService = airtelAuthService;
        this.restTemplate = new RestTemplate();
    }

    public String initiatePayment(
            AirtelPaymentRequest request
    ) {

        String token =
                airtelAuthService.getAccessToken();

        String url =
                baseUrl + "/merchant/v1/payments/";

        HttpHeaders headers =
                new HttpHeaders();

        headers.setBearerAuth(token);

        headers.setContentType(
                MediaType.APPLICATION_JSON
        );

        headers.set(
                "X-Country",
                country
        );

        headers.set(
                "X-Currency",
                currency
        );

        /*
         * Unique transaction ID generated by our system.
         */
        String transactionId =
                "AVIATOR-" +
                        UUID.randomUUID();

        /*
         * Airtel payment payload.
         */
        Map<String, Object> transaction =
                new HashMap<>();

        transaction.put(
                "id",
                transactionId
        );

        transaction.put(
                "amount",
                request.amount()
        );

        transaction.put(
                "country",
                country
        );

        transaction.put(
                "currency",
                currency
        );

        Map<String, Object> subscriber =
                new HashMap<>();

        subscriber.put(
                "country",
                country
        );

        subscriber.put(
                "currency",
                currency
        );

        subscriber.put(
                "msisdn",
                request.phoneNumber()
        );

        Map<String, Object> payload =
                new HashMap<>();

        payload.put(
                "reference",
                request.reference()
        );

        payload.put(
                "subscriber",
                subscriber
        );

        payload.put(
                "transaction",
                transaction
        );

        HttpEntity<Map<String, Object>> httpRequest =
                new HttpEntity<>(
                        payload,
                        headers
                );

        ResponseEntity<String> response =
                restTemplate.exchange(
                        url,
                        HttpMethod.POST,
                        httpRequest,
                        String.class
                );

        return response.getBody();
    }

    public String checkPaymentStatus(String transactionId) {
        return "checked";
    }
}